/**
 * Emits the localized country names the homepage example cards need.
 *
 * The cards used to call `getDestinationDisplayName` from
 * `services/destinationService`, which statically pulls
 * `data/countryTravelData.json` (678 KB of seasons, events and holidays) into
 * the homepage boot graph just to translate a dozen country names. On mobile
 * that dataset landed on the critical path before hydration, so every control
 * on the prerendered page stayed inert while it downloaded.
 *
 * This script extracts just the names for the countries the example cards
 * actually reference. `tests/unit/exampleTripCountryNames.test.ts` regenerates
 * the same table and fails if the checked-in file drifts from the source data.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const EXAMPLE_TRIP_COUNTRY_CODES = [
  'PT', 'IT', 'TH', 'KH', 'VN', 'LA', 'JP', 'PE', 'NZ', 'MA', 'IS',
];

export function buildExampleTripCountryNames() {
  const travelData = JSON.parse(
    fs.readFileSync(path.join(projectRoot, 'data', 'countryTravelData.json'), 'utf8'),
  );
  const localized = travelData?.localizedDestinationNames?.countries || {};

  const table = {};
  for (const code of EXAMPLE_TRIP_COUNTRY_CODES) {
    const entry = localized[code];
    if (!entry || !entry.en) {
      throw new Error(`countryTravelData.json has no localized names for ${code}`);
    }
    table[entry.en] = Object.fromEntries(
      Object.entries(entry)
        .filter(([, value]) => typeof value === 'string' && value.trim())
        .sort(([left], [right]) => left.localeCompare(right)),
    );
  }
  return table;
}

export function renderExampleTripCountryNamesModule() {
  const table = buildExampleTripCountryNames();
  const entries = Object.entries(table)
    .map(([englishName, names]) => {
      const fields = Object.entries(names)
        .map(([locale, value]) => `    ${locale}: ${JSON.stringify(value)},`)
        .join('\n');
      return `  ${JSON.stringify(englishName)}: {\n${fields}\n  },`;
    })
    .join('\n');

  return `// GENERATED by scripts/generate-example-trip-country-names.mjs — do not edit by hand.
// Run \`node scripts/generate-example-trip-country-names.mjs\` after changing
// data/countryTravelData.json or the countries used by data/exampleTripCards.ts.
//
// This exists so the homepage example cards can localize a country name without
// dragging data/countryTravelData.json (678 KB) onto the mobile boot path.

const EXAMPLE_TRIP_COUNTRY_NAMES: Record<string, Record<string, string>> = {
${entries}
};

/**
 * Localized display name for a country used by an example trip card. Falls back
 * to the English name the card carries, so an unknown country still renders.
 */
export const getExampleTripCountryDisplayName = (englishName: string, locale?: string): string => {
  const trimmed = englishName.trim();
  const names = EXAMPLE_TRIP_COUNTRY_NAMES[trimmed];
  if (!names) return trimmed;

  const localeKey = (locale || 'en').trim().toLowerCase().split('-')[0] || 'en';
  return names[localeKey] || names.en || trimmed;
};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const target = path.join(projectRoot, 'data', 'exampleTripCountryNames.generated.ts');
  fs.writeFileSync(target, renderExampleTripCountryNamesModule(), 'utf8');
  console.log(`Wrote ${path.relative(projectRoot, target)}`);
}
