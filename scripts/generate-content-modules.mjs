// Generates TypeScript modules embedding the raw markdown content that used
// to be bundled via Vite's import.meta.glob (blog posts + release updates).
// Runs automatically when next.config.ts / vitest.config.ts load, and can be
// invoked directly: node scripts/generate-content-modules.mjs
//
// Output files are gitignored; after adding/editing markdown while a dev
// server is running, restart it (or re-run this script) to pick up changes.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const targets = [
    {
        sourceDir: path.join(rootDir, 'content', 'blog'),
        keyPrefix: '../content/blog/',
        outFile: path.join(rootDir, 'services', 'generated', 'blogContent.generated.ts'),
        exportName: 'BLOG_RAW_FILES',
    },
    {
        sourceDir: path.join(rootDir, 'content', 'updates'),
        keyPrefix: '../content/updates/',
        outFile: path.join(rootDir, 'services', 'generated', 'updatesContent.generated.ts'),
        exportName: 'UPDATES_RAW_FILES',
    },
];

export const generateContentModules = () => {
    for (const { sourceDir, keyPrefix, outFile, exportName } of targets) {
        const fileNames = existsSync(sourceDir)
            ? readdirSync(sourceDir).filter((name) => name.endsWith('.md')).sort()
            : [];

        const entries = fileNames.map((name) => {
            const raw = readFileSync(path.join(sourceDir, name), 'utf8');
            return `    ${JSON.stringify(`${keyPrefix}${name}`)}: ${JSON.stringify(raw)},`;
        });

        const banner = '// AUTO-GENERATED by scripts/generate-content-modules.mjs — do not edit.\n'
            + '// Regenerated on next.config.ts / vitest.config.ts load.\n';
        const body = `${banner}export const ${exportName}: Record<string, string> = {\n${entries.join('\n')}\n};\n`;

        mkdirSync(path.dirname(outFile), { recursive: true });
        const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null;
        if (current !== body) {
            writeFileSync(outFile, body);
        }
    }
};

generateContentModules();
